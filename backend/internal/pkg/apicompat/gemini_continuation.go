package apicompat

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"io"
	"strings"
)

const (
	GeminiContinuationPrefix   = "gemini-thoughts-v1."
	GeminiContinuationMaxBytes = 128 << 10
	geminiSignatureMaxBytes    = 64 << 10
	geminiContinuationMaxCalls = 64
)

var ErrGeminiContinuation = errors.New("invalid Gemini continuation")

// The native host authenticates/encrypts the carrier with its existing custody
// keyring and binds it to the current account generation and model. No storage
// or provider credential belongs in this pure protocol converter.
type GeminiContinuationCodec interface {
	Seal([]byte) (string, error)
	Open(string) ([]byte, error)
}

type geminiContinuationItem struct {
	Kind      string `json:"kind"`
	CallID    string `json:"callId,omitempty"`
	Digest    string `json:"digest"`
	Signature string `json:"signature,omitempty"`
}

type geminiContinuation struct {
	Version  int                      `json:"version"`
	Position string                   `json:"position"`
	Items    []geminiContinuationItem `json:"items"`
}

func geminiSignature(extra *ChatExtraContent) (string, error) {
	if extra == nil || extra.Google == nil {
		return "", nil
	}
	sig := extra.Google.ThoughtSignature
	if len(sig) == 0 || len(sig) > geminiSignatureMaxBytes {
		return "", ErrGeminiContinuation
	}
	for _, c := range []byte(sig) {
		if c < 0x21 || c > 0x7e {
			return "", ErrGeminiContinuation
		}
	}
	return sig, nil
}

func geminiExtra(signature string) *ChatExtraContent {
	if signature == "" {
		return nil
	}
	return &ChatExtraContent{Google: &ChatGoogleExtraContent{ThoughtSignature: signature}}
}

// Bind only semantic fields that the Responses client returns unchanged. In
// particular, output item IDs/status may be regenerated by existing converters.
func geminiItemDigest(item ResponsesOutput) (string, error) {
	var value any
	switch item.Type {
	case "function_call":
		if item.CallID == "" || item.Name == "" || !json.Valid([]byte(item.Arguments)) {
			return "", ErrGeminiContinuation
		}
		var arguments any
		decoder := json.NewDecoder(strings.NewReader(item.Arguments))
		decoder.UseNumber()
		if decoder.Decode(&arguments) != nil {
			return "", ErrGeminiContinuation
		}
		value = []any{item.Type, item.CallID, item.Namespace, item.Name, arguments}
	case "custom_tool_call":
		if item.CallID == "" || item.Name == "" {
			return "", ErrGeminiContinuation
		}
		value = []string{item.Type, item.CallID, item.Name, item.Input}
	case "message":
		if item.Role != "assistant" || len(item.Content) > 64 {
			return "", ErrGeminiContinuation
		}
		var text strings.Builder
		for _, part := range item.Content {
			if part.Type != "output_text" && part.Type != "input_text" && part.Type != "text" {
				return "", ErrGeminiContinuation
			}
			text.WriteString(part.Text)
		}
		value = []string{item.Type, item.Role, text.String()}
	default:
		return "", ErrGeminiContinuation
	}
	raw, err := json.Marshal(value)
	if err != nil {
		return "", ErrGeminiContinuation
	}
	sum := sha256.Sum256(raw)
	return hex.EncodeToString(sum[:]), nil
}

// AttachGeminiContinuation appends one encrypted reasoning item for the whole
// provider step. It preserves exactly which parallel call carried a signature;
// signatures are never copied to other calls or replaced by dummy values.
func AttachGeminiContinuation(out *ResponsesResponse, source ChatMessage, codec GeminiContinuationCodec) error {
	return attachGeminiContinuation(out, source, codec, "after")
}

func attachGeminiContinuation(out *ResponsesResponse, source ChatMessage, codec GeminiContinuationCodec, position string) error {
	if out == nil || codec == nil || len(source.ToolCalls) > geminiContinuationMaxCalls {
		return ErrGeminiContinuation
	}
	messageSignature, err := geminiSignature(source.ExtraContent)
	if err != nil {
		return err
	}
	signatures := map[string]string{}
	for i, call := range source.ToolCalls {
		if call.ID == "" || len(call.ID) > 512 {
			return ErrGeminiContinuation
		}
		if _, duplicate := signatures[call.ID]; duplicate {
			return ErrGeminiContinuation
		}
		sig, e := geminiSignature(call.ExtraContent)
		if e != nil || i == 0 && sig == "" {
			return ErrGeminiContinuation
		}
		signatures[call.ID] = sig
	}
	if len(signatures) == 0 && messageSignature == "" {
		return nil
	}
	payload := geminiContinuation{Version: 1, Position: position, Items: []geminiContinuationItem{}}
	messageSeen := false
	for _, item := range out.Output {
		sig, include := signatures[item.CallID]
		if item.Type == "message" {
			if messageSeen {
				return ErrGeminiContinuation
			}
			messageSeen = true
			sig, include = messageSignature, true
			messageSignature = ""
		}
		if !include {
			continue
		}
		digest, e := geminiItemDigest(item)
		if e != nil {
			return e
		}
		payload.Items = append(payload.Items, geminiContinuationItem{Kind: item.Type, CallID: item.CallID, Digest: digest, Signature: sig})
		delete(signatures, item.CallID)
	}
	if len(signatures) != 0 || messageSignature != "" || len(payload.Items) == 0 || len(payload.Items) > geminiContinuationMaxCalls+1 {
		return ErrGeminiContinuation
	}
	raw, err := json.Marshal(payload)
	if err != nil || len(raw) > GeminiContinuationMaxBytes {
		return ErrGeminiContinuation
	}
	sealed, err := codec.Seal(raw)
	if err != nil || sealed == "" || len(sealed) > GeminiContinuationMaxBytes*2 {
		return ErrGeminiContinuation
	}
	out.Output = append(out.Output, ResponsesOutput{Type: "reasoning", ID: generateItemID(), Status: "completed", EncryptedContent: GeminiContinuationPrefix + sealed, Summary: []ResponsesSummary{}})
	return nil
}

// RestoreGeminiContinuation runs after the existing Responses-to-Chat mapping.
// Each carrier must match the exact original call/text and one converted target.
// Missing, cross-account/model, modified, orphaned or duplicated proof fails
// before native dispatch rather than silently degrading the conversation.
func RestoreGeminiContinuation(input json.RawMessage, chat *ChatCompletionsRequest, codec GeminiContinuationCodec) error {
	if chat == nil || codec == nil || len(input) > 4<<20 {
		return ErrGeminiContinuation
	}
	rawInput := bytes.TrimSpace(input)
	if len(rawInput) == 0 || rawInput[0] != '[' {
		return nil
	}
	var rawItems []json.RawMessage
	if json.Unmarshal(rawInput, &rawItems) != nil || len(rawItems) > 8192 {
		return ErrGeminiContinuation
	}
	items := make(map[int]ResponsesOutput)
	plainReasoning := make(map[int]bool)
	type inputCarrier struct {
		position int
		value    string
	}
	carriers := []inputCarrier{}
	for index, raw := range rawItems {
		var header struct {
			Type             string `json:"type"`
			Role             string `json:"role"`
			EncryptedContent string `json:"encrypted_content"`
		}
		if json.Unmarshal(raw, &header) != nil {
			return ErrGeminiContinuation
		}
		if header.Type == "reasoning" && header.EncryptedContent != "" {
			if !strings.HasPrefix(header.EncryptedContent, GeminiContinuationPrefix) || len(header.EncryptedContent) > GeminiContinuationMaxBytes*2+len(GeminiContinuationPrefix) {
				return ErrGeminiContinuation
			}
			carriers = append(carriers, inputCarrier{index, strings.TrimPrefix(header.EncryptedContent, GeminiContinuationPrefix)})
			if len(carriers) > 128 {
				return ErrGeminiContinuation
			}
		}
		if header.Type == "reasoning" && header.EncryptedContent == "" {
			plainReasoning[index] = true
		}
		if header.Type != "function_call" && header.Type != "custom_tool_call" && (header.Role != "assistant" || header.Type != "" && header.Type != "message") {
			continue
		}
		var item ResponsesOutput
		if json.Unmarshal(raw, &item) != nil {
			// Assistant input can legally carry a plain string content.
			var message struct {
				Role    string `json:"role"`
				Content string `json:"content"`
			}
			if header.Role != "assistant" || json.Unmarshal(raw, &message) != nil {
				return ErrGeminiContinuation
			}
			item = ResponsesOutput{Type: "message", Role: "assistant", Content: []ResponsesContentPart{{Type: "output_text", Text: message.Content}}}
		}
		if item.Type == "" {
			item.Type = "message"
		}
		items[index] = item
	}
	claimed := map[int]bool{}
	for _, carrier := range carriers {
		raw, err := codec.Open(carrier.value)
		if err != nil || len(raw) > GeminiContinuationMaxBytes {
			return ErrGeminiContinuation
		}
		var payload geminiContinuation
		decoder := json.NewDecoder(bytes.NewReader(raw))
		decoder.DisallowUnknownFields()
		if decoder.Decode(&payload) != nil || decoder.Decode(new(any)) != io.EOF || payload.Version != 1 || (payload.Position != "before" && payload.Position != "after") || len(payload.Items) == 0 || len(payload.Items) > geminiContinuationMaxCalls+1 {
			return ErrGeminiContinuation
		}
		// Codex intentionally omits message IDs. Bind the exact adjacent output
		// group instead: buffered responses append the carrier, while streaming
		// emits it before terminal item events. This placement is authenticated.
		direction := 1
		if payload.Position == "after" {
			direction = -1
		}
		group := make([]int, 0, len(payload.Items))
		for i := carrier.position + direction; len(group) < len(payload.Items); i += direction {
			if i < 0 || i >= len(rawItems) {
				return ErrGeminiContinuation
			}
			if _, ok := items[i]; ok {
				group = append(group, i)
			} else if !plainReasoning[i] {
				return ErrGeminiContinuation
			}
		}
		if direction == -1 {
			for left, right := 0, len(group)-1; left < right; left, right = left+1, right-1 {
				group[left], group[right] = group[right], group[left]
			}
		}
		for offset, entry := range payload.Items {
			if len(entry.Digest) != 64 || len(entry.CallID) > 512 {
				return ErrGeminiContinuation
			}
			if entry.Signature != "" {
				if _, err := geminiSignature(geminiExtra(entry.Signature)); err != nil {
					return err
				}
			}
			index := group[offset]
			item := items[index]
			digest, err := geminiItemDigest(item)
			if claimed[index] || item.Type != entry.Kind || item.CallID != entry.CallID || err != nil || digest != entry.Digest {
				return ErrGeminiContinuation
			}
			claimed[index] = true
			occurrence := 0
			if item.Type == "message" {
				for i := 0; i < index; i++ {
					prior, ok := items[i]
					if !ok || prior.Type != "message" {
						continue
					}
					if priorDigest, e := geminiItemDigest(prior); e == nil && priorDigest == digest {
						occurrence++
					}
				}
			}
			if err := restoreGeminiItem(chat, item, entry.Signature, occurrence); err != nil {
				return err
			}
		}
	}
	for _, message := range chat.Messages {
		if len(message.ToolCalls) > 0 {
			sig, err := geminiSignature(message.ToolCalls[0].ExtraContent)
			if err != nil || sig == "" {
				return ErrGeminiContinuation
			}
		}
	}
	return nil
}

func restoreGeminiItem(chat *ChatCompletionsRequest, item ResponsesOutput, signature string, occurrence int) error {
	matched := 0
	for mi := range chat.Messages {
		message := &chat.Messages[mi]
		if message.Role != "assistant" {
			continue
		}
		if item.Type == "message" {
			text := ""
			for _, part := range item.Content {
				text += part.Text
			}
			if chatMessageContentText(message.Content) == text {
				if occurrence > 0 {
					occurrence--
					continue
				}
				if message.ExtraContent != nil {
					return ErrGeminiContinuation
				}
				message.ExtraContent = geminiExtra(signature)
				return nil
			}
			continue
		}
		for ti := range message.ToolCalls {
			call := &message.ToolCalls[ti]
			if call.ID == item.CallID {
				if call.ExtraContent != nil {
					return ErrGeminiContinuation
				}
				call.ExtraContent = geminiExtra(signature)
				matched++
			}
		}
	}
	if matched != 1 {
		return ErrGeminiContinuation
	}
	return nil
}

// GeminiContinuationStream retains only bounded opaque extension bytes. The
// existing Chat stream state remains the sole owner of call IDs/arguments/text.
type GeminiContinuationStream struct {
	message string
	calls   map[int]string
	bytes   int
}

func NewGeminiContinuationStream() *GeminiContinuationStream {
	return &GeminiContinuationStream{calls: map[int]string{}}
}

func (s *GeminiContinuationStream) Observe(chunk *ChatCompletionsChunk) error {
	if s == nil || chunk == nil || len(chunk.Choices) > 1 {
		return ErrGeminiContinuation
	}
	keep := func(old *string, extra *ChatExtraContent) error {
		sig, err := geminiSignature(extra)
		if err != nil {
			return err
		}
		if sig == "" {
			return nil
		}
		if *old != "" {
			if *old != sig {
				return ErrGeminiContinuation
			}
			return nil
		}
		s.bytes += len(sig)
		if s.bytes > GeminiContinuationMaxBytes {
			return ErrGeminiContinuation
		}
		*old = sig
		return nil
	}
	for _, choice := range chunk.Choices {
		if choice.Index != 0 {
			return ErrGeminiContinuation
		}
		if err := keep(&s.message, choice.Delta.ExtraContent); err != nil {
			return err
		}
		for _, call := range choice.Delta.ToolCalls {
			index := 0
			if call.Index != nil {
				index = *call.Index
			}
			if index < 0 || index >= geminiContinuationMaxCalls {
				return ErrGeminiContinuation
			}
			sig := s.calls[index]
			if err := keep(&sig, call.ExtraContent); err != nil {
				return err
			}
			s.calls[index] = sig
		}
	}
	return nil
}

func (s *GeminiContinuationStream) Finalize(state *ChatCompletionsToResponsesStreamState, codec GeminiContinuationCodec) ([]ResponsesStreamEvent, error) {
	if s == nil || state == nil || state.CompletedSent || len(state.ToolCalls) > geminiContinuationMaxCalls {
		return nil, ErrGeminiContinuation
	}
	message := ChatMessage{Role: "assistant", ExtraContent: geminiExtra(s.message)}
	for i := 0; i < len(state.ToolCalls); i++ {
		call := state.ToolCalls[i]
		if call == nil {
			return nil, ErrGeminiContinuation
		}
		copy := *call
		copy.ExtraContent = geminiExtra(s.calls[i])
		message.ToolCalls = append(message.ToolCalls, copy)
	}
	firstSequence := state.SequenceNumber
	events := FinalizeChatCompletionsResponsesStream(state)
	if len(events) == 0 || events[len(events)-1].Response == nil {
		return nil, ErrGeminiContinuation
	}
	response := events[len(events)-1].Response
	before := len(response.Output)
	if err := attachGeminiContinuation(response, message, codec, "before"); err != nil {
		return nil, err
	}
	if len(response.Output) == before {
		return events, nil
	}
	carrier := response.Output[before]
	added := carrier
	added.Status, added.EncryptedContent = "in_progress", ""
	proof := []ResponsesStreamEvent{
		{Type: "response.output_item.added", OutputIndex: before, Item: &added},
		{Type: "response.output_item.done", OutputIndex: before, Item: &carrier},
	}
	// Prepend to the terminal batch: tools can be dispatched as soon as their
	// done event arrives, so their authenticated continuation must arrive first.
	events = append(proof, events...)
	for i := range events {
		events[i].SequenceNumber = firstSequence + i
	}
	state.SequenceNumber += len(proof)
	return events, nil
}
